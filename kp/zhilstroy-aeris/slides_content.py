def li(items, cls="ul"):
    return '<ul class="%s">%s</ul>' % (cls, "".join('<li>%s</li>' % x for x in items))

def calc(rows, total=None, extra=None):
    h = "".join('<div><span>%s</span><span>%s</span></div>' % r for r in rows)
    if total: h += '<div class="tot"><span>%s</span><span>%s</span></div>' % total
    if extra: h += '<div><span>%s</span><span>%s</span></div>' % extra
    return '<div class="calc">%s</div>' % h

def option(eyebrow, title, price, price_sub, intro, bullets, calc_html, caveat, pick=False):
    return (
      '<div class="opt%s">' % (' opt--pick' if pick else '') +
      ('<span class="flag">Рекомендуем</span>' if pick else '') +
      '<div class="opt-top"><span class="eyebrow">%s</span><h3>%s</h3>'
      '<div class="price">%s<small>%s</small></div></div>' % (eyebrow, title, price, price_sub) +
      '<div class="opt-body"><p class="tiny">%s</p>%s%s<p class="caveat">%s</p></div></div>'
      % (intro, li(bullets), calc_html, caveat))

def shot(idx, title, desc, tag, tag3d=False):
    return ('<div class="shot-item"><div class="hd"><span class="idx">%s</span>'
            '<span class="ttl">%s</span></div><p>%s</p>'
            '<div class="tagrow"><span class="tag%s">%s</span></div></div>'
            % (idx, title, desc, ' tag--3d' if tag3d else '', tag))

def cmp_block(label, vals):
    names = ["1 · Улучшение", "2 · Гибрид", "3 · CGI-рендер"]
    rows = "".join('<div class="cmp-row%s"><span class="cmp-v">%s</span><span class="cmp-val">%s</span></div>'
                   % (" cmp-row--pick" if i == 1 else "", names[i], vals[i]) for i in range(3))
    return '<div class="cmp-block"><div class="cmp-label">%s</div>%s</div>' % (label, rows)

def tier(level, title, price, bullets, dark=False):
    return ('<div class="tier%s"><span class="eyebrow">%s</span><h3>%s</h3>'
            '<div class="price">%s<small>за минуту готового ролика</small></div>%s</div>'
            % (' tier--top' if dark else '', level, title, price, li(bullets)))

def step(n, title, text):
    return '<div class="step"><div class="s">Шаг %s</div><b>%s</b><p>%s</p></div>' % (n, title, text)


